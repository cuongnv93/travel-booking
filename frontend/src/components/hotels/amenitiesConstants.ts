export function getAmenityIcon(amenity: string): string {
  if (!amenity) return '✓';
  if (AMENITY_ICONS[amenity]) return AMENITY_ICONS[amenity];
  const normalized = NORMALIZED_AMENITY_KEYS[amenity.trim().toLowerCase()];
  if (normalized && AMENITY_ICONS[normalized]) return AMENITY_ICONS[normalized];
  const lower = amenity.toLowerCase();
  if (lower.includes('wifi')) return '📶';
  if (lower.includes('hồ bơi') || lower.includes('pool')) return '🏊';
  if (lower.includes('spa')) return '💆';
  if (lower.includes('biển') || lower.includes('beach')) return '🏖️';
  if (lower.includes('nhà hàng') || lower.includes('dining')) return '🍽️';
  if (lower.includes('golf')) return '⛳';
  if (lower.includes('gym')) return '🏋️';
  if (lower.includes('ban công') || lower.includes('balcony')) return '🌅';
  return '✓';
}

export function getLocalizedAmenity(amenity: string, locale: string): string {
  if (!amenity) return '';
  if (locale === 'vi' || !locale) return amenity;
  const exact = AMENITY_TRANSLATIONS[amenity];
  if (exact) return exact[locale] || exact.en || amenity;
  const normalizedKey = NORMALIZED_AMENITY_KEYS[amenity.trim().toLowerCase()];
  if (normalizedKey) {
    const matched = AMENITY_TRANSLATIONS[normalizedKey];
    return matched?.[locale] || matched?.en || amenity;
  }
  return amenity;
}

